import { strings } from '../strings';
import { contentPages } from './contentPages';
import { hubPage, provinceHubs } from './provinceHubs';
import { FOOTER_PROVINCE_SLUGS, METHODOLOGY_SLUG } from './siteLinks';

// The copy rules for every page the site writes: nothing here may name another
// site's product, claim a check against the tax agency, or say where the site works.
function everyString(value: unknown): string[] {
  if (typeof value === 'string') return [value];
  if (Array.isArray(value)) return value.flatMap(everyString);
  if (typeof value === 'object' && value !== null) {
    return Object.values(value).flatMap(everyString);
  }
  return [];
}

const hubs = FOOTER_PROVINCE_SLUGS.map((slug) => {
  const text = provinceHubs.find((hub) => hub.slug === slug);
  if (!text) throw new Error(`no hub text for ${slug}`);
  const other = FOOTER_PROVINCE_SLUGS.filter((s) => s !== slug).map((s) => ({
    label: strings.siteNav.provinceNames[s],
    href: `/${s}/`,
  }));
  return hubPage(
    text,
    strings.siteNav.provinceNames[slug],
    [{ label: '$30,000', href: `/${slug}/30000/` }],
    new Set(),
    other,
  );
});
const methodology = contentPages.filter((p) => p.slug === METHODOLOGY_SLUG);

// Built from pieces so this file does not hold the phrases it forbids.
const CHECKED = ['checked', 'against'].join(' ');
const ONLY_IN = ['only', 'in', 'canada'].join('[\\s-]+');
const ONLY_CANADA = ['canada', 'only'].join('[\\s-]+');
const CALC_NEXT_TO_AGENCY = [
  'cra[^.]{0,40}calculator',
  'calculator[^.]{0,40}\\bcra\\b',
].join('|');
const THIRD_PARTY = ['tax', 'tips'].join('\\s*');

const rules: [string, RegExp][] = [
  ['a claim of being checked against the agency', new RegExp(CHECKED, 'i')],
  ['"only in Canada"', new RegExp(ONLY_IN, 'i')],
  ['"Canada-only"', new RegExp(ONLY_CANADA, 'i')],
  ['an AI note', /\bAI\b|artificial intelligence|generated by/i],
  [
    'the agency next to the word calculator',
    new RegExp(CALC_NEXT_TO_AGENCY, 'i'),
  ],
  ['the name of a third-party site', new RegExp(THIRD_PARTY, 'i')],
  ['a docs/ path', /docs\//i],
];

describe('copy guard', () => {
  it('covers the three hubs and the methodology page', () => {
    expect(hubs).toHaveLength(3);
    expect(methodology).toHaveLength(1);
  });

  it.each(rules)('no hub or methodology string holds %s', (_name, pattern) => {
    for (const page of [...hubs, ...methodology]) {
      for (const text of everyString(page)) {
        expect(text, `${page.slug}: ${text}`).not.toMatch(pattern);
      }
    }
  });

  it('the patterns do catch what they are for', () => {
    const samples: [number, string][] = [
      [0, 'It was checked against the agency'],
      [1, 'Only in Canada'],
      [2, 'a Canada-only site'],
      [3, 'Written by an AI'],
      [4, `the ${['CRA', 'calculator'].join(' ')}`],
      [5, `see ${['Tax', 'Tips'].join('')}`],
      [6, 'see docs/readme'],
    ];
    for (const [at, text] of samples) {
      expect(text).toMatch(rules[at]?.[1] ?? /^$/);
    }
  });

  it('uses the plain wording: the published forms, never a claim of a check', () => {
    const words = everyString(methodology).join(' ');
    expect(words).toContain('published forms');
  });
});
